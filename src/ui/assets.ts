// Card image URLs (docs/assets.md). Always relative to BASE_URL so a sub-path deployment works.

import type { CardId } from '../engine';

export type BackIndex = 0 | 1 | 2 | 3;

export const DEFAULT_BACK: BackIndex = 2;

export function logoUrl(): string {
  return `${import.meta.env.BASE_URL}skatastisches-logo.png`;
}

/**
 * Resolves a relative asset path against the page URL. A url() inside a CSS custom property that is
 * used by a stylesheet (the felt mask) resolves against the CSS file, which lies in assets/, so the
 * stamp needs an absolute URL.
 */
export function resolveAssetUrl(path: string, base: string): string {
  return new URL(path, base).href;
}

/** The club logo as a worn stamp mask for the felt (generated by scripts/make-textures.mjs). */
export function stampUrl(): string {
  return resolveAssetUrl(`${import.meta.env.BASE_URL}felt-stamp.webp`, document.baseURI);
}

export function cardUrl(id: CardId): string {
  return `${import.meta.env.BASE_URL}cards/${id}.webp`;
}

export function backUrl(index: BackIndex): string {
  return `${import.meta.env.BASE_URL}backs/${String(index)}.webp`;
}
